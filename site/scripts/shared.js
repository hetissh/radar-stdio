// The midpoint of the widest free gap on a ring: where a new piece should go.
function freeBearing(taken){
 if(!taken.length)return 0;
 const sorted=[...taken].sort((a,b)=>a-b);let widest=0,at=0;
 sorted.forEach((b,i)=>{const gap=(i+1<sorted.length?sorted[i+1]:sorted[0]+360)-b;if(gap>widest){widest=gap;at=b+gap/2;}});
 return Math.round(at%360*10)/10;
}
